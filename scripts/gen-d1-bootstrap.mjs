// Generates src/db/bootstrap.generated.ts from the local SQLite database.
// The statements are idempotent (IF NOT EXISTS / INSERT OR IGNORE) and tables
// are emitted in foreign-key dependency order so D1 can enforce constraints.
import Database from "better-sqlite3";
import { writeFileSync } from "node:fs";

const source = process.argv[2] ?? "data/vista-kigali.db";
const target = process.argv[3] ?? "src/db/bootstrap.generated.ts";

const database = new Database(source, { readonly: true });

const objects = database
  .prepare(
    "select type, name, sql from sqlite_master where sql is not null and name not like 'sqlite_%'",
  )
  .all();

const tables = database
  .prepare(
    "select name from sqlite_master where type = 'table' and name not like 'sqlite_%' and name not like '__drizzle%'",
  )
  .all()
  .map((row) => row.name);

// Dependency order: a table is emitted after every table it references.
const dependencies = new Map();
for (const table of tables) {
  const parents = database
    .prepare(`pragma foreign_key_list("${table}")`)
    .all()
    .map((row) => row.table)
    .filter((parent) => parent !== table && tables.includes(parent));
  dependencies.set(table, parents);
}

const ordered = [];
const state = new Map();
function visit(table) {
  if (state.get(table) === 2) return;
  if (state.get(table) === 1) return; // circular reference; keep existing order
  state.set(table, 1);
  for (const parent of dependencies.get(table) ?? []) visit(parent);
  state.set(table, 2);
  ordered.push(table);
}
tables.forEach(visit);

function literal(value) {
  if (value === null || value === undefined) return "NULL";
  if (typeof value === "number") return Number.isFinite(value) ? String(value) : "NULL";
  if (typeof value === "bigint") return value.toString();
  if (typeof value === "boolean") return value ? "1" : "0";
  if (value instanceof Uint8Array || Buffer.isBuffer(value)) return `X'${Buffer.from(value).toString("hex")}'`;
  return `'${String(value).replace(/'/g, "''")}'`;
}

function idempotent(sql) {
  return sql
    .replace(/^CREATE TABLE\s+(?!IF NOT EXISTS)/i, "CREATE TABLE IF NOT EXISTS ")
    .replace(/^CREATE UNIQUE INDEX\s+(?!IF NOT EXISTS)/i, "CREATE UNIQUE INDEX IF NOT EXISTS ")
    .replace(/^CREATE INDEX\s+(?!IF NOT EXISTS)/i, "CREATE INDEX IF NOT EXISTS ");
}

const statements = [];

for (const table of ordered) {
  const definition = objects.find((object) => object.type === "table" && object.name === table);
  if (definition) statements.push(idempotent(definition.sql));
}

for (const table of ordered) {
  const rows = database.prepare(`select * from "${table}"`).all();
  for (const row of rows) {
    const columns = Object.keys(row);
    if (columns.length === 0) continue;
    statements.push(
      `insert or ignore into "${table}" (${columns.map((column) => `"${column}"`).join(", ")}) values (${columns
        .map((column) => literal(row[column]))
        .join(", ")})`,
    );
  }
}

for (const object of objects) {
  if (object.type === "table") continue;
  if (object.type === "index") {
    const table = ordered.find((name) => object.sql.includes(`ON \`${name}\``) || object.sql.includes(`ON ${name}`));
    if (table) statements.push(idempotent(object.sql));
    continue;
  }
  statements.push(object.sql);
}

database.close();

const output = `// Generated by scripts/gen-d1-bootstrap.mjs — do not edit by hand.\n// ${statements.length} statements copied from ${source}.\nexport const BOOTSTRAP_STATEMENTS: string[] = ${JSON.stringify(statements)};\n`;

writeFileSync(target, output);
console.log(`Wrote ${statements.length} statements to ${target}`);
